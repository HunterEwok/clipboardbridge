# Writes the winget manifest of a release, its three files, to OUTDIR:
#
#   sh packaging/winget/manifest.sh vX.Y.Z path/to/SHA256SUMS OUTDIR [BASE_URL]
#
# The package HunterEwok.clipboardbridge installs the release's zip for
# Windows (x64 or ARM64) as winget's portable command cbb: winget unpacks
# the zip into its own folder and puts cbb.exe on PATH, nothing more. An
# administrator then runs cbb install, which runs the installer from the
# same zip (packaging\windows\install.ps1: the service, the agent, the
# firewall rules). The checksums come from the release's SHA256SUMS;
# BASE_URL, the releases' download directory by default, lets CI point at
# other archives.
#
# The release workflow writes it after each release; it goes to winget's
# repository microsoft/winget-pkgs by a pull request (docs/maintaining.md,
# "winget").
set -eu

if [ $# -lt 3 ] || [ $# -gt 4 ]; then
	echo "usage: sh packaging/winget/manifest.sh vX.Y.Z SHA256SUMS OUTDIR [BASE_URL]" >&2
	exit 2
fi
tag=$1 sums=$2 out=$3
case $tag in
v[0-9]*) ;;
*)
	echo "manifest.sh: the tag $tag does not start with v and a number" >&2
	exit 2
	;;
esac
version=${tag#v}
repo=https://github.com/HunterEwok/clipboardbridge
base=${4:-$repo/releases/download/$tag}
id=HunterEwok.clipboardbridge
schema=1.6.0

# sum NAME prints the checksum of the archive NAME in capitals, as winget
# writes it, or fails.
sum() {
	s=$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$sums")
	case $s in
	[0-9a-f]*)
		if [ ${#s} -eq 64 ]; then
			echo "$s" | tr 'a-f' 'A-F'
			return
		fi
		;;
	esac
	echo "manifest.sh: $sums has no checksum for $1" >&2
	exit 1
}
x64=$(sum clipboardbridge-windows-amd64.zip)
arm64=$(sum clipboardbridge-windows-arm64.zip)

mkdir -p "$out"
header="# Generated by packaging/winget/manifest.sh in $repo from the release $tag."

cat >"$out/$id.yaml" <<MANIFEST
$header
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.version.$schema.schema.json
PackageIdentifier: $id
PackageVersion: $version
DefaultLocale: en-US
ManifestType: version
ManifestVersion: $schema
MANIFEST

cat >"$out/$id.installer.yaml" <<MANIFEST
$header
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.installer.$schema.schema.json
PackageIdentifier: $id
PackageVersion: $version
MinimumOSVersion: 10.0.17763.0
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: clipboardbridge\\cbb.exe
    PortableCommandAlias: cbb
Installers:
  - Architecture: x64
    InstallerUrl: $base/clipboardbridge-windows-amd64.zip
    InstallerSha256: $x64
  - Architecture: arm64
    InstallerUrl: $base/clipboardbridge-windows-arm64.zip
    InstallerSha256: $arm64
ManifestType: installer
ManifestVersion: $schema
MANIFEST

cat >"$out/$id.locale.en-US.yaml" <<MANIFEST
$header
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.defaultLocale.$schema.schema.json
PackageIdentifier: $id
PackageVersion: $version
PackageLocale: en-US
Publisher: HunterEwok
PublisherUrl: https://github.com/HunterEwok
PackageName: clipboardbridge
PackageUrl: $repo
License: AGPL-3.0-only
LicenseUrl: $repo/blob/$tag/LICENSE
ShortDescription: One clipboard for the computers and phones on your home network
Description: >-
  clipboardbridge syncs the clipboard between Linux computers, Windows PCs, Macs and
  phones on the home network, end to end encrypted. After winget installs cbb, run
  cbb install in an administrator terminal to install the service.
Moniker: cbb
Tags:
  - clipboard
  - sync
ReleaseNotesUrl: $repo/releases/tag/$tag
ManifestType: defaultLocale
ManifestVersion: $schema
MANIFEST
