# Writes the Homebrew formula of a release to standard output:
#
#   sh packaging/homebrew/formula.sh vX.Y.Z path/to/SHA256SUMS [BASE_URL]
#
# The formula installs the release's archive for the Mac (Apple silicon or
# Intel) or for Linux (x86-64 or ARM64): cbb and packaging/, nothing built,
# so it needs no compiler and no Apple signing; Homebrew downloads with curl,
# which leaves no quarantine on the binary. The checksums come from the
# release's SHA256SUMS. BASE_URL, the releases' download directory by
# default, lets CI install archives from a local directory.
#
# The release workflow pushes it to the tap HunterEwok/homebrew-clipboardbridge
# (docs/maintaining.md, "Homebrew").
set -eu

if [ $# -lt 2 ] || [ $# -gt 3 ]; then
	echo "usage: sh packaging/homebrew/formula.sh vX.Y.Z SHA256SUMS [BASE_URL]" >&2
	exit 2
fi
tag=$1 sums=$2
case $tag in
v[0-9]*) ;;
*)
	echo "formula.sh: the tag $tag does not start with v and a number" >&2
	exit 2
	;;
esac
version=${tag#v}
repo=https://github.com/HunterEwok/clipboardbridge
base=${3:-$repo/releases/download/$tag}

# sum NAME prints the checksum of the archive NAME, or fails.
sum() {
	s=$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$sums")
	case $s in
	[0-9a-f]*)
		if [ ${#s} -eq 64 ]; then
			echo "$s"
			return
		fi
		;;
	esac
	echo "formula.sh: $sums has no checksum for $1" >&2
	exit 1
}
mac_arm=$(sum clipboardbridge-darwin-arm64.tar.gz)
mac_intel=$(sum clipboardbridge-darwin-amd64.tar.gz)
linux_arm=$(sum clipboardbridge-linux-arm64.tar.gz)
linux_intel=$(sum clipboardbridge-linux-amd64.tar.gz)

cat <<FORMULA
# Generated by packaging/homebrew/formula.sh in $repo from the release $tag.
# Do not edit: the next release replaces it.
class Clipboardbridge < Formula
  desc "One clipboard for the computers and phones on your home network"
  homepage "$repo"
  version "$version"
  license "AGPL-3.0-only"

  on_macos do
    on_arm do
      url "$base/clipboardbridge-darwin-arm64.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base/clipboardbridge-darwin-amd64.tar.gz"
      sha256 "$mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "$base/clipboardbridge-linux-arm64.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base/clipboardbridge-linux-amd64.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "cbb"
    pkgshare.install "packaging"
  end

  def caveats
    if OS.mac?
      <<~EOS
        The service and the pasteboard agent run from launchd. Start them, and
        restart them after each brew upgrade, with:
          sudo sh #{opt_pkgshare}/packaging/macos/install.sh --in-place #{opt_bin}/cbb
        Before brew uninstall, remove them with:
          sudo sh #{opt_pkgshare}/packaging/macos/uninstall.sh
      EOS
    else
      <<~EOS
        The service runs from systemd, with its own copy of cbb in /usr/local/bin.
        Install it, and update it after each brew upgrade, with:
          sudo sh #{opt_pkgshare}/packaging/linux/install.sh #{opt_bin}/cbb
        Remove it with:
          sudo sh /usr/local/share/clipboardbridge/uninstall.sh
      EOS
    end
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/cbb version")
  end
end
FORMULA
